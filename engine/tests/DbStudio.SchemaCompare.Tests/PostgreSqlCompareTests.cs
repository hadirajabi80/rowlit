using DbStudio.Core.SchemaCompare;

namespace DbStudio.SchemaCompare.Tests;

/// <summary>Scratch schemas cmp_src / cmp_dst in the PostgreSQL sample database (the shop schemas are never touched).</summary>
public sealed class PostgreSqlCompareTests
{
    private static IEnumerable<string> Common(string s) =>
    [
        $"CREATE SCHEMA {s}",
        $"CREATE TYPE {s}.status_t AS ENUM ('new', 'paid')",
        $"CREATE TABLE {s}.countries (id integer PRIMARY KEY, name text NOT NULL)",
    ];

    private static IEnumerable<string> Source(string s) => Common(s).Concat(
    [
        $"CREATE SEQUENCE {s}.order_numbers START WITH 1000 INCREMENT BY 1",
        $"CREATE TABLE {s}.customers (id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name varchar(100) NOT NULL, email varchar(200) UNIQUE, phone varchar(30), " +
        $"country_id integer REFERENCES {s}.countries (id), created_at timestamptz NOT NULL DEFAULT now(), CONSTRAINT ck_customers_name CHECK (length(name) > 0))",
        $"CREATE TABLE {s}.products (id integer PRIMARY KEY, name text NOT NULL, price numeric(10,2), sku varchar(20) UNIQUE)",
        $"CREATE TABLE {s}.orders (id integer PRIMARY KEY, customer_id integer NOT NULL REFERENCES {s}.customers (id) ON DELETE CASCADE, " +
        $"total numeric(12,2) NOT NULL DEFAULT 0, status {s}.status_t NOT NULL DEFAULT 'new')",
        $"CREATE INDEX ix_orders_customer ON {s}.orders (customer_id, total)",
        $"CREATE TABLE {s}.order_lines (order_id integer NOT NULL REFERENCES {s}.orders (id), product_id integer NOT NULL REFERENCES {s}.products (id), qty integer NOT NULL, PRIMARY KEY (order_id, product_id))",
        $"CREATE TABLE {s}.reviews (id integer PRIMARY KEY, customer_id integer NOT NULL REFERENCES {s}.customers (id), body text)",
        $"COMMENT ON TABLE {s}.reviews IS 'Customer reviews'",
        $"CREATE VIEW {s}.customer_orders AS SELECT c.id AS customer_id, c.name, count(o.id) AS orders FROM {s}.customers c LEFT JOIN {s}.orders o ON o.customer_id = c.id GROUP BY c.id, c.name",
        $"CREATE VIEW {s}.v_new_only AS SELECT id, name FROM {s}.countries",
        $"CREATE FUNCTION {s}.fn_tax(amount numeric) RETURNS numeric LANGUAGE sql IMMUTABLE AS $$ SELECT amount * 0.19 $$",
        $"CREATE FUNCTION {s}.fn_tax(amount numeric, rate numeric) RETURNS numeric LANGUAGE sql IMMUTABLE AS $$ SELECT amount * rate $$",
        $"CREATE FUNCTION {s}.fn_only_source() RETURNS integer LANGUAGE sql AS $$ SELECT 1 $$",
        $"CREATE FUNCTION {s}.orders_check() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN IF NEW.total < 0 THEN RAISE EXCEPTION 'negative total'; END IF; RETURN NEW; END $$",
        $"CREATE PROCEDURE {s}.touch_order(p_id integer) LANGUAGE plpgsql AS $$ BEGIN UPDATE {s}.orders SET total = total WHERE id = p_id; END $$",
        $"CREATE TRIGGER trg_orders_check BEFORE INSERT ON {s}.orders FOR EACH ROW EXECUTE FUNCTION {s}.orders_check()",
    ]);

    private static IEnumerable<string> Target(string s) => Common(s).Concat(
    [
        $"CREATE SEQUENCE {s}.order_numbers START WITH 1000 INCREMENT BY 5",
        $"CREATE TABLE {s}.customers (id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name varchar(100) NOT NULL, email varchar(100) UNIQUE, nickname varchar(30), " +
        $"country_id integer REFERENCES {s}.countries (id), created_at timestamptz NOT NULL DEFAULT now(), CONSTRAINT ck_customers_name CHECK (length(name) > 1))",
        $"CREATE TABLE {s}.products (id integer PRIMARY KEY, name text NOT NULL, price numeric(8,2), sku varchar(20))",
        $"CREATE TABLE {s}.orders (id integer PRIMARY KEY, customer_id integer NOT NULL REFERENCES {s}.customers (id), " +
        $"total numeric(12,2) NOT NULL DEFAULT 0, status {s}.status_t NOT NULL DEFAULT 'new')",
        $"CREATE INDEX ix_orders_customer ON {s}.orders (customer_id)",
        $"CREATE TABLE {s}.order_lines (order_id integer NOT NULL REFERENCES {s}.orders (id), product_id integer NOT NULL REFERENCES {s}.products (id), qty integer NOT NULL, PRIMARY KEY (order_id, product_id))",
        $"CREATE TABLE {s}.legacy_audit (id integer PRIMARY KEY, customer_id integer REFERENCES {s}.customers (id), note text)",
        $"CREATE VIEW {s}.customer_orders AS SELECT c.id AS customer_id, c.name FROM {s}.customers c",
        $"CREATE VIEW {s}.v_old AS SELECT id FROM {s}.countries",
        $"CREATE FUNCTION {s}.fn_tax(amount numeric) RETURNS numeric LANGUAGE sql IMMUTABLE AS $$ SELECT amount * 0.2 $$",
        $"CREATE FUNCTION {s}.fn_tax(amount numeric, rate numeric) RETURNS numeric LANGUAGE sql IMMUTABLE AS $$ SELECT amount * rate $$",
        $"CREATE FUNCTION {s}.fn_only_target() RETURNS integer LANGUAGE sql AS $$ SELECT 2 $$",
        $"CREATE FUNCTION {s}.orders_check() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN RETURN NEW; END $$",
        $"CREATE PROCEDURE {s}.touch_order(p_id integer) LANGUAGE plpgsql AS $$ BEGIN UPDATE {s}.orders SET total = total WHERE id = p_id; END $$",
    ]);

    private static IEnumerable<string> Cleanup(string s) => [$"DROP SCHEMA IF EXISTS {s} CASCADE"];

    private static readonly Dictionary<string, string> Expected = new()
    {
        ["table:customers"] = CompareStatus.Alter,
        ["table:products"] = CompareStatus.Alter,
        ["table:orders"] = CompareStatus.Alter,
        ["table:reviews"] = CompareStatus.Create,
        ["table:legacy_audit"] = CompareStatus.Drop,
        ["view:customer_orders"] = CompareStatus.Alter,
        ["view:v_new_only"] = CompareStatus.Create,
        ["view:v_old"] = CompareStatus.Drop,
        ["func:fn_tax(amount numeric)"] = CompareStatus.Alter,
        ["func:fn_only_source()"] = CompareStatus.Create,
        ["func:fn_only_target()"] = CompareStatus.Drop,
        ["func:orders_check()"] = CompareStatus.Alter,
        ["trigger:trg_orders_check"] = CompareStatus.Create,
        ["sequence:order_numbers"] = CompareStatus.Alter,
    };

    [SkippableFact]
    public async Task Compare_Script_Apply_ThenIdentical()
    {
        var pg = Servers.Pg;
        Skip.IfNot(await Servers.ReachableAsync(pg.Host, pg.Port), "PostgreSQL sample server is not reachable.");
        using var env = new CompareEnv();
        var conn = env.Add("pg", "postgresql", Servers.PgProps(), pg.Password);
        var (result, script) = await ScratchRunner.RunAsync(env, new Scratch(conn, "shop", "cmp_src", "cmp_dst", Source, Target, Cleanup, Expected));
        Assert.True(result.TransactionalDdl);
        Assert.True(script.TransactionalDdl);
    }
}
