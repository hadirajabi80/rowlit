using DbStudio.Core.SchemaCompare;

namespace DbStudio.SchemaCompare.Tests;

/// <summary>Scratch users (schemas) CMP_SRC / CMP_DST on the Oracle sample server, created and dropped as SYSTEM.</summary>
public sealed class OracleCompareTests
{
    private static IEnumerable<string> Common(string s) =>
    [
        $"CREATE USER {s} IDENTIFIED BY \"Cmp_Scratch_2026\" QUOTA UNLIMITED ON USERS",
        $"CREATE TABLE {s}.countries (id NUMBER(10) NOT NULL PRIMARY KEY, name VARCHAR2(100) NOT NULL)",
    ];

    private static IEnumerable<string> Source(string s) => Common(s).Concat(
    [
        $"CREATE SEQUENCE {s}.order_numbers START WITH 1000 INCREMENT BY 1",
        $"CREATE TABLE {s}.customers (id NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name VARCHAR2(100) NOT NULL, email VARCHAR2(200) UNIQUE, phone VARCHAR2(30), " +
        $"country_id NUMBER(10) REFERENCES {s}.countries (id), created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL, CONSTRAINT ck_customers_name CHECK (LENGTH(name) > 0))",
        $"CREATE TABLE {s}.products (id NUMBER(10) NOT NULL PRIMARY KEY, name VARCHAR2(100) NOT NULL, price NUMBER(10,2), sku VARCHAR2(20) UNIQUE)",
        $"CREATE TABLE {s}.orders (id NUMBER(10) NOT NULL PRIMARY KEY, customer_id NUMBER(10) NOT NULL REFERENCES {s}.customers (id) ON DELETE CASCADE, " +
        $"total NUMBER(12,2) DEFAULT 0 NOT NULL, status VARCHAR2(20) DEFAULT 'new' NOT NULL)",
        $"CREATE INDEX {s}.ix_orders_customer ON {s}.orders (customer_id, total)",
        $"CREATE TABLE {s}.reviews (id NUMBER(10) NOT NULL PRIMARY KEY, customer_id NUMBER(10) NOT NULL REFERENCES {s}.customers (id), body CLOB)",
        $"CREATE VIEW {s}.customer_orders AS SELECT c.id AS customer_id, c.name, COUNT(o.id) AS orders FROM {s}.customers c LEFT JOIN {s}.orders o ON o.customer_id = c.id GROUP BY c.id, c.name",
        $"CREATE VIEW {s}.v_new_only AS SELECT id, name FROM {s}.countries",
        $"CREATE FUNCTION {s}.fn_tax (amount NUMBER) RETURN NUMBER IS BEGIN RETURN amount * 0.19; END;",
        $"CREATE FUNCTION {s}.fn_only_source RETURN NUMBER IS BEGIN RETURN 1; END;",
        $"CREATE PROCEDURE {s}.touch_order (p_id NUMBER) IS BEGIN UPDATE {s}.orders SET total = total WHERE id = p_id; END;",
        $"CREATE TRIGGER {s}.trg_orders_check BEFORE INSERT ON {s}.orders FOR EACH ROW BEGIN IF :NEW.total < 0 THEN RAISE_APPLICATION_ERROR(-20001, 'negative total'); END IF; END;",
    ]);

    private static IEnumerable<string> Target(string s) => Common(s).Concat(
    [
        $"CREATE SEQUENCE {s}.order_numbers START WITH 1000 INCREMENT BY 5",
        $"CREATE TABLE {s}.customers (id NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name VARCHAR2(100) NOT NULL, email VARCHAR2(100) UNIQUE, nickname VARCHAR2(30), " +
        $"country_id NUMBER(10) REFERENCES {s}.countries (id), created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL, CONSTRAINT ck_customers_name CHECK (LENGTH(name) > 1))",
        $"CREATE TABLE {s}.products (id NUMBER(10) NOT NULL PRIMARY KEY, name VARCHAR2(100) NOT NULL, price NUMBER(8,2), sku VARCHAR2(20))",
        $"CREATE TABLE {s}.orders (id NUMBER(10) NOT NULL PRIMARY KEY, customer_id NUMBER(10) NOT NULL REFERENCES {s}.customers (id), " +
        $"total NUMBER(12,2) DEFAULT 0 NOT NULL, status VARCHAR2(20) DEFAULT 'new' NOT NULL)",
        $"CREATE INDEX {s}.ix_orders_customer ON {s}.orders (customer_id)",
        $"CREATE TABLE {s}.legacy_audit (id NUMBER(10) NOT NULL PRIMARY KEY, customer_id NUMBER(10) REFERENCES {s}.customers (id), note CLOB)",
        $"CREATE VIEW {s}.customer_orders AS SELECT c.id AS customer_id, c.name FROM {s}.customers c",
        $"CREATE VIEW {s}.v_old AS SELECT id FROM {s}.countries",
        $"CREATE FUNCTION {s}.fn_tax (amount NUMBER) RETURN NUMBER IS BEGIN RETURN amount * 0.2; END;",
        $"CREATE FUNCTION {s}.fn_only_target RETURN NUMBER IS BEGIN RETURN 2; END;",
        $"CREATE PROCEDURE {s}.touch_order (p_id NUMBER) IS BEGIN UPDATE {s}.orders SET total = total WHERE id = p_id; END;",
        $"CREATE TRIGGER {s}.trg_old BEFORE DELETE ON {s}.orders FOR EACH ROW BEGIN NULL; END;",
    ]);

    private static IEnumerable<string> Cleanup(string s) => [$"DROP USER {s} CASCADE"];

    private static readonly Dictionary<string, string> Expected = new()
    {
        ["table:CUSTOMERS"] = CompareStatus.Alter,
        ["table:PRODUCTS"] = CompareStatus.Alter,
        ["table:ORDERS"] = CompareStatus.Alter,
        ["table:REVIEWS"] = CompareStatus.Create,
        ["table:LEGACY_AUDIT"] = CompareStatus.Drop,
        ["view:CUSTOMER_ORDERS"] = CompareStatus.Alter,
        ["view:V_NEW_ONLY"] = CompareStatus.Create,
        ["view:V_OLD"] = CompareStatus.Drop,
        ["func:FN_TAX"] = CompareStatus.Alter,
        ["func:FN_ONLY_SOURCE"] = CompareStatus.Create,
        ["func:FN_ONLY_TARGET"] = CompareStatus.Drop,
        ["trigger:TRG_ORDERS_CHECK"] = CompareStatus.Create,
        ["trigger:TRG_OLD"] = CompareStatus.Drop,
        ["sequence:ORDER_NUMBERS"] = CompareStatus.Alter,
    };

    [SkippableFact]
    public async Task Compare_Script_Apply_ThenIdentical()
    {
        var o = Servers.Oracle;
        Skip.IfNot(await Servers.ReachableAsync(o.Host, o.Port), "Oracle sample server is not reachable.");
        using var env = new CompareEnv();
        var conn = env.Add("oracle", "oracle", Servers.OracleProps(), o.Password);
        var (result, script) = await ScratchRunner.RunAsync(env, new Scratch(conn, null, "CMP_SRC", "CMP_DST", Source, Target, Cleanup, Expected));
        // Oracle commits every DDL statement
        Assert.False(result.TransactionalDdl);
        Assert.Contains("\n/", script.Text);
    }
}
